<?php

namespace ingeniousai\domainguard\core;

/**
 * Takedown Packets (Pro) — for every registered lookalike in a
 * completed report, a ready-to-send registrar abuse report built ONLY
 * from facts the scan actually observed (registration, MX state, the
 * impersonation technique, the score and cert count at observation
 * time). Ported 1:1 from the WordPress plugin's DGFS_Takedown.
 */
class Takedown
{
    /**
     * All packets for a completed report: one per registered lookalike.
     *
     * @param mixed $report Completed gateway report.
     * @return array[] Packet arrays (see packet()).
     */
    public static function packets($report): array
    {
        $out = [];
        if (!ReportData::isReport($report)) {
            return $out;
        }
        if (empty($report['lookalikes_registered']) || !is_array($report['lookalikes_registered'])) {
            return $out;
        }
        foreach ($report['lookalikes_registered'] as $lk) {
            if (is_array($lk) && !empty($lk['perm'])) {
                $out[] = self::packet($report, $lk);
            }
        }
        return $out;
    }

    /**
     * One takedown packet for one registered lookalike.
     *
     * @param array $report    Completed gateway report.
     * @param array $lookalike One entry of lookalikes_registered:
     *                         {perm, fuzzer, mx}.
     * @return array{domain:string,lookalike:string,fuzzer:string,has_mx:bool,steps:string[],text:string}
     */
    public static function packet(array $report, array $lookalike): array
    {
        $domain = isset($report['domain']) ? (string) $report['domain'] : '';
        $perm = isset($lookalike['perm']) ? (string) $lookalike['perm'] : '';
        $fuzzer = isset($lookalike['fuzzer']) ? (string) $lookalike['fuzzer'] : '';
        $has_mx = !empty($lookalike['mx']);
        $when = '';
        if (!empty($report['generated_at'])) {
            $ts = strtotime((string) $report['generated_at']);
            if ($ts) {
                $when = gmdate('M j, Y', $ts);
            }
        }

        $steps = [
            'File the abuse report below with the lookalike\'s registrar (find it via the ICANN lookup at lookup.icann.org — the registrar\'s abuse contact is listed there).',
            'Report the domain to Google Safe Browsing (safebrowsing.google.com/safebrowsing/report_phish) and Microsoft SmartScreen if it serves a phishing page.',
            $has_mx
                ? 'This lookalike accepts mail — warn your customers and staff explicitly, and consider a DMARC policy of p=reject on your own domain so spoofed mail fails.'
                : 'This lookalike does not currently accept mail (no MX observed) — the web/impersonation route matters most.',
            'If the lookalike uses your trademark, a UDRP complaint is the ownership route; the abuse report below is the fast first step either way.',
        ];

        $lines = [];
        $lines[] = 'ABUSE REPORT — lookalike domain impersonation risk';
        $lines[] = '';
        $lines[] = 'My domain: ' . $domain;
        $lines[] = 'Lookalike domain: ' . $perm;
        if ($fuzzer) {
            $lines[] = 'Impersonation technique detected: ' . $fuzzer;
        }
        if ($when) {
            $lines[] = 'Observed: ' . $when . ' (DomainGuard exposure scan)';
        }
        $lines[] = '';
        $lines[] = 'Evidence collected by the scan:';
        $lines[] = ' - The lookalike domain is registered and resolves in DNS.';
        $lines[] = $has_mx
            ? ' - The lookalike publishes MX records — it can receive mail addressed to the impersonated brand.'
            : ' - The lookalike does not publish MX records at observation time.';
        $lines[] = ' - My domain\'s exposure score at observation: ' . (isset($report['score']) ? (int) $report['score'] : 0) . '/100.';
        $lines[] = ' - Certificates logged for my domain in certificate-transparency logs at observation: ' . (isset($report['ct_cert_count']) ? (int) $report['ct_cert_count'] : 0) . '.';
        $lines[] = '';
        $lines[] = 'Requested action: review this domain for phishing / brand-impersonation abuse under your acceptable-use policy and suspend it if the review confirms impersonation.';
        $lines[] = '';
        $lines[] = 'Generated by DomainGuard Domain Watch (Craft CMS plugin) from a real scan of my own domain.';

        return [
            'domain' => $domain,
            'lookalike' => $perm,
            'fuzzer' => $fuzzer,
            'has_mx' => $has_mx,
            'steps' => $steps,
            'text' => implode("\n", $lines),
        ];
    }
}
